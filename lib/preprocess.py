def get_smote_data(X, y, n, seed=RANDOM_SEED):
    sm = SMOTE(random_state=seed)
    X_res, y_res = sm.fit_resample(X, y)

    X_synthetic = X_res.iloc[len(X):]
    y_synthetic = y_res.iloc[len(y):]

    # sample together before resetting index
    combined = X_synthetic.copy()
    combined['__target__'] = y_synthetic.values
    combined = combined.sample(n=n, random_state=seed).reset_index(drop=True)

    y_out = combined.pop('__target__')
    return combined, y_out

## Generated by Claude
def get_ctgan_data(X, y, n, discrete_columns=None, epochs=300):
    # smash X and y together since ctgan wants one dataframe
    target_col = y.name or "target"
    df = X.copy()
    df[target_col] = y.values

    # figure out which columns are categorical if we weren't told
    if discrete_columns is None:
        discrete_columns = list(
            df.select_dtypes(include=["object", "category"]).columns
        )

    # target should always be discrete (it's a class label)
    if target_col not in discrete_columns:
        discrete_columns.append(target_col)

    # train and generate
    model = CTGAN(epochs=epochs, verbose=True)
    model.fit(df, discrete_columns=discrete_columns)
    synthetic_df = model.sample(n)

    # split back out
    X_aug = synthetic_df.drop(columns=[target_col]).reset_index(drop=True)
    y_aug = synthetic_df[target_col].reset_index(drop=True)

    return X_aug, y_aug

