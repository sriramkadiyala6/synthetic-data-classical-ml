def preprocess_adult(X):
    df = X.copy()

    # drop unhelpful columns
    df = df.drop(columns=["fnlwgt", "education"])

    # binary encode sex
    df["sex"] = (df["sex"] == "Male").astype(int)

    # OHE for nominal categoricals
    ohe_cols = ["workclass", "occupation", "native-country",
                "marital-status", "relationship", "race"]

    encoder = OneHotEncoder(sparse_output=False, handle_unknown="ignore")
    ohe_array = encoder.fit_transform(df[ohe_cols])
    ohe_df = pd.DataFrame(ohe_array, columns=encoder.get_feature_names_out(ohe_cols), index=df.index)

    # drop original cols and attach encoded ones
    df = df.drop(columns=ohe_cols)
    df = pd.concat([df, ohe_df], axis=1)

    return df, encoder

def preprocess_adult_encoder(X, encoder):
    df = X.copy()

    df = df.drop(columns=["fnlwgt", "education"])
    df["sex"] = (df["sex"] == "Male").astype(int)

