## Generated by claude
def sample_n_rows(X, y, n, seed=RANDOM_SEED):
    if n > len(X):
        print(f"Warning: requested {n} rows but only {len(X)} available, returning all rows")
    n = min(n, len(X))
    idx = (pd.Series(range(len(X))).sample(n=n, random_state=seed).index)
    X_sample = X.iloc[idx].reset_index(drop=True)
    y_sample = y.iloc[idx].reset_index(drop=True)
    return X_sample, y_sample

## Generated by claude
def combine_datasets(X1, y1, X2, y2, pct_from_1, seed=RANDOM_SEED):
    """
    Combine two datasets, sampling pct_from_1 (0.0-1.0) fraction from dataset 1
    and the remainder from dataset 2. Total size is min(len1/pct, len2/(1-pct))
    to avoid oversampling either source.
    """
    rng = np.random.default_rng(seed)

    # If percentage is given as a 0-100 integer, convert to decimal
    if pct_from_1 > 1:
        pct_from_1 = pct_from_1 / 100

    n_total = min(len(X1) / pct_from_1, len(X2) / (1 - pct_from_1))
    n1 = int(n_total * pct_from_1)
    n2 = int(n_total * (1 - pct_from_1))

    idx1 = rng.choice(len(X1), size=n1, replace=False)
    idx2 = rng.choice(len(X2), size=n2, replace=False)

    X_combined = pd.concat([X1.iloc[idx1], X2.iloc[idx2]], ignore_index=True)
    y_combined = pd.concat([y1.iloc[idx1], y2.iloc[idx2]], ignore_index=True)

    # Shuffle so dataset 1 and 2 samples aren't all bunched together
    shuffle_idx = rng.permutation(len(X_combined))
    return X_combined.iloc[shuffle_idx].reset_index(drop=True), \
           y_combined.iloc[shuffle_idx].reset_index(drop=True)

