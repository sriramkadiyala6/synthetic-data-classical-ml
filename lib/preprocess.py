def import_and_combine_heart(paths, impute=True):
    col_names = ['age', 'sex', 'cp', 'trestbps', 'chol', 'fbs',
                 'restecg', 'thalach', 'exang', 'oldpeak', 'slope',
                 'ca', 'thal', 'target']

    dfs = []
    for path in paths:
        df = pd.read_csv(path, header=None, names=col_names, na_values='?')
        dfs.append(df)

    combined = pd.concat(dfs, ignore_index=True)
    combined['target'] = (combined['target'] > 0).astype(int)

    if impute:
        for col in ['trestbps', 'chol', 'thalach', 'oldpeak', 'ca']:
            combined[col] = combined[col].fillna(combined[col].median())
        for col in ['slope', 'thal', 'fbs', 'restecg', 'exang']:
            combined[col] = combined[col].fillna(combined[col].mode()[0])

    combined = combined.dropna().reset_index(drop=True)

    X = combined.drop(columns=['target'])
    y = combined['target']

    return X, y

